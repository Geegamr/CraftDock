use std::path::{Path, PathBuf};

/// Reads CF_API_KEY from a dotenv-style file without pulling in a dependency.
fn read_env_key(file: &Path) -> Option<String> {
    let contents = std::fs::read_to_string(file).ok()?;
    for line in contents.lines() {
        let line = line.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        let Some((name, value)) = line.split_once('=') else {
            continue;
        };
        let name = name.trim().trim_start_matches("export ").trim();
        if name != "CF_API_KEY" {
            continue;
        }
        let value = value
            .trim()
            .trim_matches(|character| character == '"' || character == '\'');
        if !value.is_empty() {
            return Some(value.to_string());
        }
    }
    None
}

/// Per-build mask bytes so the key never sits in the binary as readable text.
fn random_bytes(length: usize) -> Vec<u8> {
    let mut seed = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|elapsed| elapsed.as_nanos() as u64)
        .unwrap_or(0x9E37_79B9_7F4A_7C15)
        ^ (u64::from(std::process::id()) << 32);
    (0..length)
        .map(|_| {
            seed ^= seed << 13;
            seed ^= seed >> 7;
            seed ^= seed << 17;
            (seed >> 24) as u8
        })
        .collect()
}

fn byte_array(bytes: &[u8]) -> String {
    let items: Vec<String> = bytes.iter().map(u8::to_string).collect();
    format!("[{}]", items.join(", "))
}

/// Writes the masked key into OUT_DIR so main.rs can `include!` it.
fn write_embedded_key(out_dir: &Path, key: &str) {
    let plain = key.as_bytes();
    let mask = random_bytes(plain.len());
    let masked: Vec<u8> = plain.iter().zip(mask.iter()).map(|(byte, mask)| byte ^ mask).collect();

    let source = format!(
        "// Generated by build.rs. The CurseForge key is stored masked, never as text.\n\
         pub const KEY_DATA: [u8; {}] = {};\n\
         pub const KEY_MASK: [u8; {}] = {};\n",
        masked.len(),
        byte_array(&masked),
        mask.len(),
        byte_array(&mask),
    );

    let target = out_dir.join("embedded_key.rs");
    std::fs::write(&target, source).expect("failed to write the embedded key module");
}

fn main() {
    tauri_build::build();

    // Embed the developer key at compile time so a copied release exe reaches
    // CurseForge without a .env beside it. The value comes from the environment
    // or the gitignored project .env; only the compiled binary holds it.
    let manifest_dir = PathBuf::from(
        std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR is set by cargo"),
    );
    let project_root = manifest_dir.parent().unwrap_or(&manifest_dir).to_path_buf();
    let project_env = project_root.join(".env");
    let local_env = manifest_dir.join("craftdock.env");

    println!("cargo:rerun-if-changed={}", project_env.display());
    println!("cargo:rerun-if-changed={}", local_env.display());
    println!("cargo:rerun-if-env-changed=CF_API_KEY");

    let key = std::env::var("CF_API_KEY")
        .ok()
        .map(|value| value.trim().to_string())
        .filter(|value| !value.is_empty())
        .or_else(|| read_env_key(&project_env))
        .or_else(|| read_env_key(&local_env));

    let out_dir = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR is set by cargo"));
    write_embedded_key(&out_dir, key.as_deref().unwrap_or(""));
}

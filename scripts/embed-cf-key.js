// Embeds the CurseForge API key into packaged Electron builds.
//
// The key is read from CF_API_KEY or the project .env and written to cf-key.js
// as a masked byte array, which main.js decodes in memory. Nothing readable is
// stored in the app, and cf-key.js is generated output that stays out of git.
const crypto = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');

const projectRoot = path.resolve(__dirname, '..');
const outputFile = path.join(projectRoot, 'cf-key.js');

function readKeyFromEnvFile(file) {
  if (!fs.existsSync(file)) return '';
  for (const rawLine of fs.readFileSync(file, 'utf8').split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith('#')) continue;
    const separator = line.indexOf('=');
    if (separator === -1) continue;
    const name = line.slice(0, separator).trim().replace(/^export\s+/, '');
    if (name !== 'CF_API_KEY') continue;
    return line.slice(separator + 1).trim().replace(/^['"]|['"]$/g, '').trim();
  }
  return '';
}

const key = String(process.env.CF_API_KEY || '').trim() || readKeyFromEnvFile(path.join(projectRoot, '.env'));

const plain = Buffer.from(key, 'utf8');
const mask = crypto.randomBytes(plain.length);
const data = Buffer.alloc(plain.length);
for (let index = 0; index < plain.length; index += 1) data[index] = plain[index] ^ mask[index];

fs.writeFileSync(
  outputFile,
  '// Generated by scripts/embed-cf-key.js at build time. Do not commit.\n'
    + '// The key is masked; main.js decodes it in memory.\n'
    + `module.exports = { data: [${Array.from(data).join(', ')}], mask: [${Array.from(mask).join(', ')}] };\n`,
);

console.log(key
  ? 'CurseForge key embedded in cf-key.js for packaged builds.'
  : 'No CF_API_KEY found; packaged builds will report CurseForge as not configured.');
